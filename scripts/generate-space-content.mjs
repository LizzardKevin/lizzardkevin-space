function addUiRows(targetRows, namespace, enValue, zhValue, startOrder) {
  const enLeaves = flattenLeaves(enValue);
  const zhByPath = new Map(flattenLeaves(zhValue).map((item) => [item.path, item.value]));
  enLeaves.forEach((leaf, index) => {
    targetRows.push(rowWithDefaults({
      entry_kind: "ui_copy",
      id: `${namespace}_${leaf.path.replace(/[^a-z0-9]+/gi, "_")}`,
      enabled: "Y",
      order: String(startOrder + index),
      ui_namespace: namespace,
      ui_path: leaf.path,
      value_en: String(leaf.value ?? ""),
      value_zh: String(zhByPath.get(leaf.path) ?? ""),
    }));
  });
}

