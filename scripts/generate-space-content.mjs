function fail(message) {
  throw new Error(message);
}

function ensureDir(dir) {
  fs.mkdirSync(dir, { recursive: true });
}

function normalizeCell(value) {
  if (value === undefined || value === null) return "";
  return String(value).replace(/\r\n/g, "\n").trim();
}

function splitList(value) {
  return normalizeCell(value)
    .split("\n")
    .map((item) => item.trim())
    .filter(Boolean);
}

function splitUnique(value) {
  return Array.from(new Set(splitList(value)));
}

function readJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, "utf8"));
}

function writeJsonString(value) {
  return `${JSON.stringify(value, null, 2)}\n`;
}

function writeTsModule(exports) {
  return `/* Auto-generated by scripts/generate-space-content.mjs. Do not edit by hand. */\n\n${exports.join("\n\n")}\n`;
}

function literal(value) {
  return JSON.stringify(value, null, 2);
}

function writeIfChanged(filePath, content, changes) {
  if (fs.existsSync(filePath) && fs.readFileSync(filePath, "utf8") === content) return;
  changes.push(filePath);
  if (!checkMode) {
    ensureDir(path.dirname(filePath));
    fs.writeFileSync(filePath, content);
  }
}

function parseTuple(value, fieldName, id) {
  const parts = normalizeCell(value).split(",").map((part) => Number(part.trim()));
  if (parts.length !== 3 || parts.some((part) => !Number.isFinite(part))) {
    fail(`${id} ${fieldName} must be three comma-separated numbers`);
  }
  return parts;
}

function parseNumber(value, fallback, fieldName, id) {
  const cell = normalizeCell(value);
  if (!cell) return fallback;
  const number = Number(cell);
  if (!Number.isFinite(number)) fail(`${id} ${fieldName} must be a number`);
  return number;
}

function required(row, field) {
  const value = normalizeCell(row[field]);
  if (!value) fail(`${row.entry_kind}:${row.id} missing required ${field}`);
  return value;
}

function enumValue(row, field, requiredField = false) {
  const value = normalizeCell(row[field]);
  if (!value) {
    if (requiredField) fail(`${row.entry_kind}:${row.id} missing required ${field}`);
    return "";
  }
  const allowed = enumFields[field];
  if (!allowed?.has(value)) {
    fail(`${row.entry_kind}:${row.id} ${field} must be one of ${Array.from(allowed).join(", ")}`);
  }
  return value;
}

function localized(row, fieldBase, requiredField = false) {
  const en = normalizeCell(row[`${fieldBase}_en`]);
  const zh = normalizeCell(row[`${fieldBase}_zh`]);
  if (requiredField && (!en || !zh)) {
    fail(`${row.entry_kind}:${row.id} missing bilingual ${fieldBase}`);
  }
  return { en, zh };
}

function localizedArray(row, fieldBase) {
  return {
    en: splitUnique(row[`${fieldBase}_en`]),
    zh: splitUnique(row[`${fieldBase}_zh`]),
  };
}

