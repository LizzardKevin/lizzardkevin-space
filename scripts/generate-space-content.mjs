function rowEnabled(row) {
  const enabled = normalizeCell(row.enabled).toLowerCase();
  return enabled !== "n" && enabled !== "no" && enabled !== "false" && enabled !== "0";
}

function sortRows(rows) {
  return [...rows].sort((a, b) => {
    const orderA = Number(normalizeCell(a.order)) || 0;
    const orderB = Number(normalizeCell(b.order)) || 0;
    return orderA - orderB || normalizeCell(a.id).localeCompare(normalizeCell(b.id));
  });
}

function readWorkbookRows() {
  if (!fs.existsSync(workbookPath)) fail(`Missing workbook: ${workbookPath}`);
  const workbook = XLSX.readFile(workbookPath, { cellDates: false });
  if (
    workbook.SheetNames.length !== requiredSheets.length ||
    requiredSheets.some((sheetName, index) => workbook.SheetNames[index] !== sheetName)
  ) {
    fail(`Workbook sheets must be exactly ${requiredSheets.join(", ")}; found ${workbook.SheetNames.join(", ")}`);
  }

  const rows = [];
  for (const sheetName of requiredSheets) {
    const sheet = workbook.Sheets[sheetName];
    const sheetRows = XLSX.utils.sheet_to_json(sheet, { defval: "", raw: false });
    if (sheetRows.length === 0) fail(`${sheetName} sheet must include a header row and at least one data row`);
    const sheetHeaders = Object.keys(sheetRows[0]);
    for (const header of ["entry_kind", "id", "enabled", "order"]) {
      if (!sheetHeaders.includes(header)) fail(`${sheetName} missing header ${header}`);
    }
    for (const row of sheetRows) {
      const normalized = Object.fromEntries(headers.map((header) => [header, normalizeCell(row[header])]));
      if (!normalized.entry_kind && !normalized.id) continue;
      normalized.sheet = sheetName;
      rows.push(normalized);
    }
  }
  return rows.filter(rowEnabled);
}

function flattenLeaves(value, prefix = "", output = []) {
  if (value === null || typeof value !== "object") {
    output.push({ path: prefix, value });
    return output;
  }
  if (Array.isArray(value)) {
    value.forEach((item, index) => flattenLeaves(item, prefix ? `${prefix}.${index}` : String(index), output));
    return output;
  }
  for (const [key, child] of Object.entries(value)) {
    flattenLeaves(child, prefix ? `${prefix}.${key}` : key, output);
  }
  return output;
}

function setDeepValue(target, dottedPath, value) {
  const parts = dottedPath.split(".");
  let current = target;
  for (let index = 0; index < parts.length; index += 1) {
    const part = parts[index];
    const nextPart = parts[index + 1];
    const last = index === parts.length - 1;
    if (last) {
      current[part] = value;
      return;
    }
    if (current[part] === undefined) {
      current[part] = /^\d+$/.test(nextPart) ? [] : {};
    }
    current = current[part];
  }
}

function buildUiCopy(rows, namespace) {
  const bundle = { en: {}, zh: {} };
  for (const row of sortRows(rows.filter((item) => item.entry_kind === "ui_copy" && item.ui_namespace === namespace))) {
    const uiPath = required(row, "ui_path");
    setDeepValue(bundle.en, uiPath, normalizeCell(row.value_en));
    setDeepValue(bundle.zh, uiPath, normalizeCell(row.value_zh));
  }
  return bundle;
}

