function buildProfileBundle(language, identityRows, linkRows, sectionRows) {
  const identityRow = identityRows[0];
  if (!identityRow) fail("Missing profile_identity row");
  return {
    identity: {
      name: required(identityRow, "title_en"),
      displayName: required(identityRow, `title_${language}`),
      roles: splitList(identityRow[`tags_${language}`]),
      location: required(identityRow, "asset_path"),
      status: required(identityRow, `status_${language}`),
      bio: required(identityRow, `overview_${language}`),
    },
    links: linkRows.map((row) => ({
      label: required(row, `title_${language}`),
      value: required(row, `value_${language}`),
      ...(normalizeCell(row.asset_path) ? { href: normalizeCell(row.asset_path) } : {}),
    })),
    sections: sectionRows.map((row) => ({
      id: row.id,
      number: required(row, "number"),
      title: required(row, `title_${language}`),
      subtitle: required(row, `profile_subtitle_${language}`),
      summary: required(row, `overview_${language}`),
      details: splitList(row[`profile_details_${language}`]),
      fill: splitList(row[`profile_fill_${language}`]),
      spaceUse: required(row, `profile_space_use_${language}`),
      tags: splitUnique(row[`tags_${language}`]),
    })),
  };
}

function materializeOutputs(outputs) {
  const files = new Map();
  files.set(path.join(publicExhibitsRoot, "manifest.json"), writeJsonString(outputs.manifest));
  for (const [exhibitId, content] of Object.entries(outputs.contentByExhibit)) {
    files.set(path.join(publicExhibitsRoot, exhibitId, "content.json"), writeJsonString(content));
  }
  files.set(path.join(generatedRoot, "exhibitLabels.generated.ts"), writeTsModule([
    `export const generatedExhibitLabels = ${literal(outputs.exhibitLabels)};`,
  ]));
  files.set(path.join(generatedRoot, "mobileArchive.generated.ts"), writeTsModule([
    `export const generatedMobileTabs = ${literal(outputs.mobileTabs)};`,
    `export const generatedMobileTerminalCopy = ${literal(outputs.mobileTerminalCopy)};`,
    `export const generatedMobileProjectItems = ${literal(outputs.mobileProjectItems)};`,
    `export const generatedMobileSkillEntries = ${literal(outputs.mobileSkillEntries)};`,
  ]));
  files.set(path.join(generatedRoot, "devStories.generated.ts"), writeTsModule([
    `export const generatedDevStoriesByLanguage = ${literal(outputs.devStoriesByLanguage)};`,
  ]));
  files.set(path.join(generatedRoot, "profile.generated.ts"), writeTsModule([
    `export const generatedProfileByLanguage = ${literal(outputs.profileByLanguage)};`,
  ]));
  files.set(path.join(generatedRoot, "i18nResources.generated.ts"), writeTsModule([
    `export const generatedResources = ${literal(outputs.i18nResources)};`,
  ]));
  files.set(path.join(generatedRoot, "splitArchiveCopy.generated.ts"), writeTsModule([
    `export const generatedSplitArchiveCopy = ${literal(outputs.splitArchiveCopy)};`,
  ]));
  return files;
}

function syncOutputs(rows) {
  const files = materializeOutputs(buildOutputs(rows));
  const changes = [];
  for (const [filePath, content] of files) {
    writeIfChanged(filePath, content, changes);
  }
  if (changes.length > 0 && checkMode) {
    fail(`Generated content is out of sync:\n${changes.map((filePath) => `- ${path.relative(repoRoot, filePath)}`).join("\n")}`);
  }
  return changes;
}

