function rowWithDefaults(values) {
  return Object.fromEntries(headers.map((header) => [header, values[header] ?? ""]));
}

function readExistingAppendixRows() {
  const rowsBySheet = Object.fromEntries(requiredSheets.map((sheet) => [sheet, []]));
  if (!fs.existsSync(workbookPath)) return rowsBySheet;

  const workbook = XLSX.readFile(workbookPath, { cellDates: false });
  for (const sheetName of requiredSheets) {
    if (!workbook.SheetNames.includes(sheetName)) continue;
    const sheetRows = XLSX.utils.sheet_to_json(workbook.Sheets[sheetName], { defval: "", raw: false });
    for (const row of sheetRows) {
      const normalized = rowWithDefaults(Object.fromEntries(headers.map((header) => [header, normalizeCell(row[header])])));
      if (!normalized.entry_kind || !normalized.id) continue;
      if (normalized.entry_kind !== "asset_note" && normalized.entry_kind !== "gallery_node") continue;
      rowsBySheet[sheetName].push(normalized);
    }
  }
  return rowsBySheet;
}

